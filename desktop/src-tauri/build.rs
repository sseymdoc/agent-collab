fn main() {
    // 随包发行包的文件名在构建时定下：安装包升级时不会删掉上一版留下的资源文件，
    // 运行时只认这次构建放进去的那一个（见 helper::release）。
    println!("cargo:rerun-if-changed=resources/release");
    let bundled: Vec<String> = std::fs::read_dir("resources/release")
        .map(|entries| entries.flatten().filter_map(|e| e.file_name().into_string().ok()).filter(|n| n.starts_with("agent-collab-") && n.ends_with(".tar.gz")).collect())
        .unwrap_or_default();
    if let [name] = bundled.as_slice() {
        println!("cargo:rustc-env=AGENT_COLLAB_BUNDLED_RELEASE={name}");
    }
    // 原生桥命令。列在应用清单里之后，它们不再缺省对所有窗口开放，
    // 只有 capabilities/ 里显式授权的窗口可以调用（见 capabilities/main.json）。
    let mut commands = vec![
        "app_info",
        "connections_list",
        "connection_pair",
        "connection_open",
        "connection_close",
        "connection_forget",
        "api_request",
        "stream_open",
        "stream_close",
        "blob_save",
        "notify",
        "project_bind",
        "project_bindings",
        "project_unbind",
        "project_scan",
        "project_upload",
        "project_cancel",
        "result_download",
        "result_plan",
        "result_apply",
        "result_unfinished",
        "result_recover",
        "local_discover",
        "local_setup",
        "local_service",
        "local_pair",
    ];
    // tauri-build 把每条命令的权限写到 permissions/autogenerated/，但不清理旧文件。
    let automation_permission = "permissions/autogenerated/automation_report.toml";
    if std::env::var_os("CARGO_FEATURE_AUTOMATION").is_some() {
        commands.push("automation_report");
    } else {
        let _ = std::fs::remove_file(automation_permission);
    }
    let manifest = tauri_build::AppManifest::new().commands(commands.leak());
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest)).expect("failed to run tauri-build");
}
