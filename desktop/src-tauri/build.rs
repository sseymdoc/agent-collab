fn main() {
    // 随包发行包的文件名在构建时定下：安装包升级时不会删掉上一版留下的资源文件，
    // 运行时只认这次构建放进去的那一个（见 helper::release）。
    println!("cargo:rerun-if-changed=resources/release");
    let bundled: Vec<String> = std::fs::read_dir("resources/release")
        .map(|entries| entries.flatten().filter_map(|e| e.file_name().into_string().ok()).filter(|n| n.starts_with("agent-collab-") && n.ends_with(".tar.gz")).collect())
        .unwrap_or_default();
    if let [name] = bundled.as_slice() {
        println!("cargo:rustc-env=AGENT_COLLAB_BUNDLED_RELEASE={name}");
    }
    // 随包载荷清单（ADR 0004 第 7 条）：流水线在组装好 resources/ 之后写出 payload.json，它的摘要编进二进制，
    // 运行时据此拒绝缺文件、内容不符或混入清单外文件的载荷。开发构建没有这个文件，不做核对。
    println!("cargo:rerun-if-changed=resources/payload.json");
    if let Ok(bytes) = std::fs::read("resources/payload.json") {
        use std::fmt::Write;
        let digest = sha256(&bytes).iter().fold(String::new(), |mut s, b| {
            let _ = write!(s, "{b:02x}");
            s
        });
        println!("cargo:rustc-env=AGENT_COLLAB_PAYLOAD_SHA256={digest}");
    }
    // Windows 安装器钩子要知道本构建的本机部署在哪个前缀、哪个实例（卸载时询问是否一并卸载本机后台）。由实例名生成，
    // 不会与编进程序的实例不一致。
    println!("cargo:rerun-if-env-changed=AGENT_COLLAB_INSTANCE");
    let instance = std::env::var("AGENT_COLLAB_INSTANCE").unwrap_or_default();
    let prefix_name = if instance.is_empty() { "agent-collab".to_string() } else { format!("agent-collab-{instance}") };
    assert!(prefix_name.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-'), "实例名无效");
    let nsh = format!("; 由 build.rs 生成，不要手改。\n!define AC_PREFIX_NAME \"{prefix_name}\"\n!define AC_INSTANCE \"{instance}\"\n");
    if std::fs::read_to_string("windows/instance.nsh").ok().as_deref() != Some(nsh.as_str()) {
        std::fs::write("windows/instance.nsh", nsh).expect("写 windows/instance.nsh 失败");
    }
    // 正式身份不能带自动化钩子、实例名或测试身份的更新设置（流水线的 release_gate 另做完整核对）。
    println!("cargo:rerun-if-env-changed=AGENT_COLLAB_BUILD_KIND");
    if std::env::var("AGENT_COLLAB_BUILD_KIND").as_deref() == Ok("formal") {
        assert!(std::env::var_os("CARGO_FEATURE_AUTOMATION").is_none(), "正式版不能带 automation feature");
        assert!(instance.is_empty(), "正式版的实例名必须为空");
    }
    // 原生桥命令。列在应用清单里之后，它们不再缺省对所有窗口开放，
    // 只有 capabilities/ 里显式授权的窗口可以调用（见 capabilities/main.json）。
    let mut commands = vec![
        "app_info",
        "connections_list",
        "connection_pair",
        "connection_open",
        "connection_close",
        "connection_forget",
        "api_request",
        "stream_open",
        "stream_close",
        "blob_save",
        "notify",
        "project_bind",
        "project_bindings",
        "project_unbind",
        "project_scan",
        "project_upload",
        "project_cancel",
        "result_download",
        "result_plan",
        "result_apply",
        "result_unfinished",
        "result_recover",
        "local_discover",
        "local_setup",
        "local_service",
        "local_pair",
        "local_uninstall",
        "node_bindings",
        "node_bind",
        "node_unbind",
        "diagnostics_export",
        "diagnostics_preview",
        "diagnostics_save",
        "backup_save",
        "update_status",
        "update_settings",
        "update_check",
        "update_download",
        "update_install",
    ];
    // tauri-build 把每条命令的权限写到 permissions/autogenerated/，但不清理旧文件。
    let automation_permission = "permissions/autogenerated/automation_report.toml";
    if std::env::var_os("CARGO_FEATURE_AUTOMATION").is_some() {
        commands.push("automation_report");
    } else {
        let _ = std::fs::remove_file(automation_permission);
    }
    let manifest = tauri_build::AppManifest::new().commands(commands.leak());
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest)).expect("failed to run tauri-build");
}

/// 载荷清单的 SHA-256。
fn sha256(data: &[u8]) -> [u8; 32] {
    use sha2::Digest;
    sha2::Sha256::digest(data).into()
}
